#pragma once

// Общий системный курсор (управляется наклоном IMU, когда
// g_config.cursor_mode == 3 "IMU" в Settings -> Cursor). Используется
// экранами, которые поддерживают курсорный режим (пока: list_menu.cpp).

// true если курсорный режим включён в настройках.
bool k85_cursor_active(void);

// Сбрасывает позицию курсора в центр экрана - вызывать при входе в экран,
// который поддерживает курсор.
void k85_cursor_reset(void);

// Считывает наклон и двигает курсор - вызывать раз за кадр.
void k85_cursor_update(void);

int k85_cursor_x(void);
int k85_cursor_y(void);

// Рисует крестик курсора - вызывать последним шагом, после обычной отрисовки экрана.
void k85_cursor_draw(void);
