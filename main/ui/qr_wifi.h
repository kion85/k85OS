#pragma once
// Показывает во весь экран QR-код с данными WiFi-сети (формат "WIFI:S:...;T:...;P:...;;",
// который распознают камеры Android/iOS для быстрого подключения без ручного
// ввода пароля). Блокирует выполнение до нажатия A+B.
//
// ssid       - имя сети (буквы/цифры - без спецсимволов, см. предупреждение ниже).
// password   - пароль, или nullptr/"" для открытой сети.
// open       - true, если сеть открытая (без пароля) - тогда password игнорируется.
//
// ВНИМАНИЕ: формат WIFI: QR требует экранирования спецсимволов (';', ':', ',', '\')
// в SSID/пароле обратным слэшем. Эта функция экранирование НЕ делает - подходит
// для авто-сгенерированных k85OS SSID/паролей (только буквы и цифры), но если
// передать пользовательский пароль с этими символами, итоговый QR будет невалиден.
void k85_show_wifi_qr(const char *ssid, const char *password, bool open);